function idiomaActual() {
  var saved = localStorage.getItem("ns_lang");
  return saved === "en" ? "en" : "es";
}

function t(key, vars) {
  var dict = NS_I18N[idiomaActual()] || NS_I18N.es;
  var text = dict[key] || (NS_I18N.es[key] || key);
  if (vars) {
    Object.keys(vars).forEach(function (k) {
      text = text.replace(new RegExp("{{" + k + "}}", "g"), vars[k]);
    });
  }
  return text;
}

function productoNombre(p) {
  var key = "product." + p.id + ".name";
  var val = t(key);
  return val === key ? p.name : val;
}

function productoDesc(p) {
  var key = "product." + p.id + ".desc";
  var val = t(key);
  return val === key ? (p.description || "") : val;
}

function aplicarI18n(root) {
  var scope = root || document;
  document.documentElement.lang = idiomaActual();
  scope.querySelectorAll("[data-i18n]").forEach(function (el) {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  scope.querySelectorAll("[data-i18n-html]").forEach(function (el) {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  scope.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  document.querySelectorAll(".lang-btn").forEach(function (btn) {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === idiomaActual());
  });
}

function setLang(lang) {
  localStorage.setItem("ns_lang", lang === "en" ? "en" : "es");
  aplicarI18n();
  if (typeof actualizarNavbar === "function") actualizarNavbar();
  if (typeof refrescarAsistenteI18n === "function") refrescarAsistenteI18n();
  document.dispatchEvent(new CustomEvent("ns:lang"));
}
